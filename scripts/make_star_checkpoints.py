"""
Generate tests/fixtures_star_checkpoints.py: full-state digests of StarGOL games at fixed generations.

Initial conditions come from gollyx-maps (fixed seeds) and are written into the fixture.
Run from the repo root with gollyx-maps installed:

    python scripts/make_star_checkpoints.py
"""
import json
import os
import sys

from gollyx_maps.maps import get_map_realization
from gollyx_python import StarGOL

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)
from tests.star_digest import star_state_digest  # noqa: E402

FIXTURE_FILE = os.path.join(REPO_ROOT, "tests", "fixtures_star_checkpoints.py")
CUP = "star-viii"
ROWS, COLUMNS = 160, 240
CHECKPOINTS = [0, 1, 2, 3, 4, 5, 10, 25, 100, 500, 1000]
# (pattern, seed); the last four ship dead-wait initial conditions
GAMES = [("random", 300), ("deadendterminal", 301), ("horsewithears", 302),
         ("housewithears", 303), ("ironhorse", 304)]
IC_KEYS = [("s1", "initialConditions1"), ("s2", "initialConditions2"),
           ("b1", "initialConditionsb1"), ("b2", "initialConditionsb2"),
           ("c1", "initialConditionsc1"), ("c2", "initialConditionsc2")]


def run_game(pattern, seed):
    """
    Run one game past the last checkpoint with halting off, recording state digests.

    Args:
        pattern (str): star-viii pattern name.
        seed (int): map realization seed.

    Returns:
        dict: fixture entry with name, kwargs and checkpoints {generation: [counts, digest]}.
    """
    m = get_map_realization(CUP, pattern, rows=ROWS, columns=COLUMNS, seed=seed)
    kwargs = {k: m[ic] for k, ic in IC_KEYS if ic in m}
    kwargs.update(rows=ROWS, columns=COLUMNS, rule_b=[2], rule_s=[3, 4, 5], rule_c=4)
    gol = StarGOL(**kwargs)
    gol.halt = False
    checkpoints = {}
    while True:
        if gol.generation in CHECKPOINTS:
            counts = gol.get_live_counts()["liveCellsColors"]
            checkpoints[gol.generation] = [list(counts), star_state_digest(gol)]
        if gol.generation >= CHECKPOINTS[-1]:
            break
        gol.next_step()
    print(f"{pattern}: {checkpoints[CHECKPOINTS[-1]][0]}", flush=True)
    return {"name": f"{CUP}-{pattern}", "kwargs": kwargs, "checkpoints": checkpoints}


def main():
    entries = [run_game(p, s) for p, s in GAMES]
    lines = [
        "# Generated by scripts/make_star_checkpoints.py; do not edit by hand.",
        "# Each entry: StarGOL(**kwargs) with halt off must match counts and digest at each generation.",
        "STAR_CHECKPOINT_GAMES = [",
    ]
    for e in entries:
        lines.append("    {")
        lines.append(f'        "name": {json.dumps(e["name"])},')
        lines.append('        "kwargs": {')
        for key, value in e["kwargs"].items():
            lines.append(f'            "{key}": {value!r},')
        lines.append("        },")
        lines.append(f'        "checkpoints": {e["checkpoints"]!r},')
        lines.append("    },")
    lines.append("]")
    with open(FIXTURE_FILE, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(entries)} games to {FIXTURE_FILE}")


if __name__ == "__main__":
    main()
