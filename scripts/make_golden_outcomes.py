"""
Generate tests/fixtures_outcomes.py: run_simulation() results for a fixed set of games.

Initial conditions come from gollyx-maps (fixed seeds) or are built by hand, and are
written into the fixture so the tests do not need gollyx-maps. Run from the repo root
with gollyx-maps installed (pip install -e ".[dev]"):

    python scripts/make_golden_outcomes.py
"""
import json
import os
import sys
from concurrent.futures import ProcessPoolExecutor

from gollyx_maps.maps import get_map_realization
from gollyx_python import run_simulation

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)
from tests.fixtures_toroidal import (  # noqa: E402
    domino_party_150_240_state1,
    domino_party_150_240_state2,
)

FIXTURE_FILE = os.path.join(REPO_ROOT, "tests", "fixtures_outcomes.py")

LIFE = ([3], [2, 3])
HIGHLIFE = ([3, 6], [2, 3])

# (name, cup, pattern, rows, columns, seed, rules)
MAP_GAMES = [
    ("vi-detroit-carbomb", "vi", "detroit_carbomb", None, None, 1, LIFE),
    ("vi-butterfly-crash", "vi", "butterfly_crash", None, None, 2, LIFE),
    ("vi-quad-beatty", "vi", "quad_beatty", None, None, 3, LIFE),
    ("vi-tacoma-standoff", "vi", "tacoma_standoff", None, None, 4, LIFE),
    ("vi-west-seattle", "vi", "west_seattle", None, None, 5, LIFE),
    ("vi-random", "vi", "random", None, None, 6, LIFE),
    ("hellmouth-twoacorn", "hellmouth", "twoacorn", None, None, 7, LIFE),
    ("hellmouth-spaceshipcrash", "hellmouth", "spaceshipcrash", None, None, 8, LIFE),
    ("hellmouth-randommethuselahs", "hellmouth", "randommethuselahs", None, None, 9, LIFE),
    ("vi-random-97x151", "vi", "random", 97, 151, 11, LIFE),
    ("vi-random-b36s23", "vi", "random", None, None, 10, HIGHLIFE),
]

# Acorn for team 1; team 2's two isolated cells die in generation 1
ACORN = '[{"30":[50,51,54,55,56]},{"31":[53]},{"32":[51]}]'
TWO_LONERS = '[{"80":[20]},{"90":[100]}]'
# One blinker per team, far apart: the counts stay equal forever
BLINKER1 = '[{"20":[20,21,22]}]'
BLINKER2 = '[{"70":[90,91,92]}]'

HAND_GAMES = [
    ("vi-domino-party", dict(
        initial_conditions_1=domino_party_150_240_state1,
        initial_conditions_2=domino_party_150_240_state2,
        rows=150, columns=240,
    )),
    ("vi-domino-party-max-2000", dict(
        initial_conditions_1=domino_party_150_240_state1,
        initial_conditions_2=domino_party_150_240_state2,
        rows=150, columns=240, max_generations=2000,
    )),
    ("team2-dies-early", dict(
        initial_conditions_1=ACORN,
        initial_conditions_2=TWO_LONERS,
        rows=100, columns=120,
    )),
    ("blinkers-fixed-300", dict(
        initial_conditions_1=BLINKER1,
        initial_conditions_2=BLINKER2,
        rows=100, columns=120, fixed_ngenerations=300,
    )),
]


def build_games():
    games = []
    for name, kwargs in HAND_GAMES:
        games.append((name, dict(cup="vi", rule_b=[3], rule_s=[2, 3], **kwargs)))
    for name, cup, pattern, rows, columns, seed, (rule_b, rule_s) in MAP_GAMES:
        m = get_map_realization(cup, pattern, rows=rows, columns=columns, seed=seed)
        games.append((name, dict(
            initial_conditions_1=m["initialConditions1"],
            initial_conditions_2=m["initialConditions2"],
            rows=m["rows"],
            columns=m["columns"],
            cup="vi",
            rule_b=rule_b,
            rule_s=rule_s,
        )))
    for name, kwargs in games:
        # No wall-clock limit, so results do not depend on machine speed
        kwargs["timeout_seconds"] = 0
    return games


def play(game):
    name, kwargs = game
    result = run_simulation(**kwargs)
    print(f"{name}: {result}", flush=True)
    return result


def write_fixture(games, results):
    lines = [
        "# Generated by scripts/make_golden_outcomes.py; do not edit by hand.",
        "# Each entry: run_simulation(**kwargs) must return expected.",
        "OUTCOMES = [",
    ]
    for (name, kwargs), result in zip(games, results):
        lines.append("    {")
        lines.append(f'        "name": {json.dumps(name)},')
        lines.append('        "kwargs": {')
        for key, value in kwargs.items():
            lines.append(f'            "{key}": {value!r},')
        lines.append("        },")
        lines.append(f'        "expected": {result!r},')
        lines.append("    },")
    lines.append("]")
    with open(FIXTURE_FILE, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    games = build_games()
    with ProcessPoolExecutor() as pool:
        results = list(pool.map(play, games))
    write_fixture(games, results)
    print(f"Wrote {len(games)} games to {FIXTURE_FILE}")


if __name__ == "__main__":
    main()
